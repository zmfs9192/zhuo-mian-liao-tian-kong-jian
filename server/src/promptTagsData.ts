/**
 * The built-in prompt-tag taxonomy seeded once into prompt_tags
 * (see getPromptTree in actions.ts). The user asked for the
 * canvas to start with the most complete professional prompt-tag
 * set available （初始带最全的提示词标签）: the tree follows the
 * standard professional prompt structure — subject, appearance,
 * outfit, pose, scene, time & weather, composition, camera,
 * lighting, colour, style, quality, and a negative-prompt branch
 * — each category split into sub-groups of leaf tags. A leaf's
 * `value` is the prompt fragment it contributes when chosen on
 * the canvas (the English text image models are trained on);
 * `label` is the Chinese display name. After seeding, the rows
 * belong to the user: edits and deletions persist and this file
 * is never consulted again.
 *
 * PROMPT_TAG_INITIAL_ROOT below is a different, deliberately
 * narrower set: the canvas's 「初始状态」 (initial state) that
 * the one-click 恢复初始状态 button restores, and the seed a
 * fresh install starts from. Per the user's instruction it is
 * built ONLY from art-style / visual-style material — painting
 * style and medium, colour, lighting, composition, camera,
 * quality, negatives — with NO item/prop-type categories
 * （主体 / 服饰 / 场景之类） at all.
 */
